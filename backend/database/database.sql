-- ============================================================
-- SISTEM PERSEDIAAN BAHAN BAKU DAN BARANG JADI TOKO BUTIK
-- PostgreSQL / Supabase
-- ============================================================

-- ============================================================
-- 1. TABEL BAHAN BAKU
-- ============================================================

CREATE TABLE IF NOT EXISTS public.bahan_baku (
    id_bahan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    kode_bahan VARCHAR(20) NOT NULL UNIQUE,

    nama_bahan VARCHAR(100) NOT NULL,

    jenis_bahan VARCHAR(50),

    satuan VARCHAR(20) NOT NULL,

    stok NUMERIC(12,2) NOT NULL DEFAULT 0,

    stok_minimum NUMERIC(12,2) NOT NULL DEFAULT 0,

    aktif BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT bahan_stok_tidak_negatif
        CHECK (stok >= 0),

    CONSTRAINT bahan_stok_minimum_tidak_negatif
        CHECK (stok_minimum >= 0)
);

ALTER TABLE public.bahan_baku
ADD COLUMN IF NOT EXISTS aktif BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE public.bahan_baku
ADD COLUMN IF NOT EXISTS harga_pokok_rata_rata NUMERIC(15,4) NOT NULL DEFAULT 0;


-- ============================================================
-- 2. TABEL BARANG JADI
-- ============================================================

CREATE TABLE IF NOT EXISTS public.barang_jadi (
    id_barang BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    kode_barang VARCHAR(20) NOT NULL UNIQUE,

    nama_barang VARCHAR(100) NOT NULL,

    kategori VARCHAR(50),

    ukuran VARCHAR(10),

    warna VARCHAR(30),

    harga_jual NUMERIC(15,2) NOT NULL DEFAULT 0,

    stok INTEGER NOT NULL DEFAULT 0,

    aktif BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT barang_harga_tidak_negatif
        CHECK (harga_jual >= 0),

    CONSTRAINT barang_stok_tidak_negatif
        CHECK (stok >= 0)
);

ALTER TABLE public.barang_jadi
ADD COLUMN IF NOT EXISTS aktif BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE public.barang_jadi
ADD COLUMN IF NOT EXISTS harga_pokok_rata_rata NUMERIC(15,4) NOT NULL DEFAULT 0;


-- ============================================================
-- 3. TABEL DETAIL PRODUKSI
--
-- Menentukan bahan apa saja yang diperlukan
-- untuk membuat satu barang jadi.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.detail_produksi (
    id_detail BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_barang BIGINT NOT NULL,

    id_bahan BIGINT NOT NULL,

    jumlah_digunakan NUMERIC(12,2) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_detail_barang
        FOREIGN KEY (id_barang)
        REFERENCES public.barang_jadi(id_barang)
        ON DELETE CASCADE,

    CONSTRAINT fk_detail_bahan
        FOREIGN KEY (id_bahan)
        REFERENCES public.bahan_baku(id_bahan)
        ON DELETE CASCADE,

    CONSTRAINT unique_barang_bahan
        UNIQUE (id_barang, id_bahan),

    CONSTRAINT jumlah_bahan_harus_positif
        CHECK (jumlah_digunakan > 0)
);


-- ============================================================
-- 4. TABEL TRANSAKSI
--
-- Jenis:
-- MASUK     = bahan baku masuk
-- PRODUKSI  = menghasilkan barang jadi
-- KELUAR    = barang jadi keluar/terjual
-- ============================================================

CREATE TABLE IF NOT EXISTS public.transaksi (
    id_transaksi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    tanggal DATE NOT NULL DEFAULT CURRENT_DATE,

    jenis_transaksi VARCHAR(20) NOT NULL,

    keterangan TEXT,

    id_bahan BIGINT,

    id_barang BIGINT,

    jumlah NUMERIC(12,2) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_transaksi_bahan
        FOREIGN KEY (id_bahan)
        REFERENCES public.bahan_baku(id_bahan)
        ON DELETE RESTRICT,

    CONSTRAINT fk_transaksi_barang
        FOREIGN KEY (id_barang)
        REFERENCES public.barang_jadi(id_barang)
        ON DELETE RESTRICT,

    CONSTRAINT jenis_transaksi_valid
        CHECK (
            jenis_transaksi IN (
                'MASUK',
                'BAHAN_KELUAR',
                'PRODUKSI',
                'KELUAR'
            )
        ),

    CONSTRAINT jumlah_transaksi_harus_positif
        CHECK (jumlah > 0),

    CONSTRAINT transaksi_relasi_valid
        CHECK (
            (jenis_transaksi = 'MASUK'
                AND id_bahan IS NOT NULL
                AND id_barang IS NULL)

            OR

            (jenis_transaksi = 'BAHAN_KELUAR'
                AND id_bahan IS NOT NULL
                AND id_barang IS NULL)

            OR

            (jenis_transaksi = 'PRODUKSI'
                AND id_barang IS NOT NULL
                AND id_bahan IS NULL)

            OR

            (jenis_transaksi = 'KELUAR'
                AND id_barang IS NOT NULL
                AND id_bahan IS NULL)
        )
);

ALTER TABLE public.transaksi
ADD COLUMN IF NOT EXISTS harga_perolehan_satuan NUMERIC(15,2),
ADD COLUMN IF NOT EXISTS harga_jual_satuan NUMERIC(15,2),
ADD COLUMN IF NOT EXISTS nilai_bahan NUMERIC(15,2) NOT NULL DEFAULT 0,
ADD COLUMN IF NOT EXISTS nilai_persediaan NUMERIC(15,2) NOT NULL DEFAULT 0,
ADD COLUMN IF NOT EXISTS nilai_penjualan NUMERIC(15,2) NOT NULL DEFAULT 0,
ADD COLUMN IF NOT EXISTS biaya_produksi NUMERIC(15,2) NOT NULL DEFAULT 0,
ADD COLUMN IF NOT EXISTS metode_pembayaran VARCHAR(20);

ALTER TABLE public.transaksi
DROP CONSTRAINT IF EXISTS jenis_transaksi_valid;

ALTER TABLE public.transaksi
ADD CONSTRAINT jenis_transaksi_valid
CHECK (jenis_transaksi IN ('MASUK', 'BAHAN_KELUAR', 'PRODUKSI', 'KELUAR', 'SALDO_AWAL', 'PENILAIAN_AWAL'));

ALTER TABLE public.transaksi
DROP CONSTRAINT IF EXISTS transaksi_relasi_valid;

ALTER TABLE public.transaksi
ADD CONSTRAINT transaksi_relasi_valid
CHECK (
    (jenis_transaksi IN ('MASUK', 'BAHAN_KELUAR')
        AND id_bahan IS NOT NULL AND id_barang IS NULL)
    OR
    (jenis_transaksi IN ('PRODUKSI', 'KELUAR')
        AND id_barang IS NOT NULL AND id_bahan IS NULL)
    OR
    (jenis_transaksi = 'SALDO_AWAL'
        AND ((id_bahan IS NOT NULL AND id_barang IS NULL)
          OR (id_bahan IS NULL AND id_barang IS NOT NULL)))
    OR
    (jenis_transaksi = 'PENILAIAN_AWAL'
        AND ((id_bahan IS NOT NULL AND id_barang IS NULL)
          OR (id_bahan IS NULL AND id_barang IS NOT NULL)))
);

ALTER TABLE public.transaksi
DROP CONSTRAINT IF EXISTS transaksi_pembayaran_valid;

ALTER TABLE public.transaksi
ADD CONSTRAINT transaksi_pembayaran_valid
CHECK (
    metode_pembayaran IS NULL
    OR metode_pembayaran IN ('TUNAI', 'TRANSFER', 'QRIS', 'DEBIT')
);

ALTER TABLE public.transaksi
DROP CONSTRAINT IF EXISTS transaksi_nilai_nonnegatif;

ALTER TABLE public.transaksi
ADD CONSTRAINT transaksi_nilai_nonnegatif
CHECK (
    (harga_perolehan_satuan IS NULL OR harga_perolehan_satuan >= 0)
    AND (harga_jual_satuan IS NULL OR harga_jual_satuan >= 0)
    AND nilai_bahan >= 0
    AND nilai_persediaan >= 0
    AND nilai_penjualan >= 0
    AND biaya_produksi >= 0
);

CREATE TABLE IF NOT EXISTS public.jurnal_umum (
    id_jurnal BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaksi BIGINT NOT NULL REFERENCES public.transaksi(id_transaksi) ON DELETE RESTRICT,
    tanggal DATE NOT NULL,
    akun VARCHAR(100) NOT NULL,
    debit NUMERIC(15,2) NOT NULL DEFAULT 0,
    kredit NUMERIC(15,2) NOT NULL DEFAULT 0,
    keterangan TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT jurnal_satu_sisi_positif CHECK (
        (debit > 0 AND kredit = 0) OR (kredit > 0 AND debit = 0)
    )
);

CREATE INDEX IF NOT EXISTS idx_jurnal_tanggal ON public.jurnal_umum(tanggal);
CREATE INDEX IF NOT EXISTS idx_jurnal_transaksi ON public.jurnal_umum(id_transaksi);


-- ============================================================
-- INDEX
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_bahan_nama
ON public.bahan_baku(nama_bahan);

CREATE INDEX IF NOT EXISTS idx_barang_nama
ON public.barang_jadi(nama_barang);

CREATE INDEX IF NOT EXISTS idx_transaksi_tanggal
ON public.transaksi(tanggal);

CREATE INDEX IF NOT EXISTS idx_transaksi_jenis
ON public.transaksi(jenis_transaksi);


-- ============================================================
-- FUNCTION:
-- MENGUPDATE STOK SETELAH TRANSAKSI
-- ============================================================

CREATE OR REPLACE FUNCTION public.proses_transaksi_stok()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    detail RECORD;
    kebutuhan NUMERIC(12,2);
    stok_bahan_saat_ini NUMERIC(12,2);
    harga_unit NUMERIC(15,4);
    harga_bahan_saat_ini NUMERIC(15,4);
    biaya_bahan_total NUMERIC(15,2) := 0;
    nilai_produksi_total NUMERIC(15,2) := 0;
BEGIN
    IF NEW.jenis_transaksi = 'PENILAIAN_AWAL' THEN
        IF COALESCE(NEW.harga_perolehan_satuan, 0) <= 0 THEN
            RAISE EXCEPTION 'Harga perolehan saldo lama wajib lebih dari 0';
        END IF;

        IF NEW.id_bahan IS NOT NULL THEN
            UPDATE public.bahan_baku
            SET harga_pokok_rata_rata = NEW.harga_perolehan_satuan
            WHERE id_bahan = NEW.id_bahan
              AND stok > 0
              AND harga_pokok_rata_rata = 0
              AND stok = NEW.jumlah;
        ELSE
            UPDATE public.barang_jadi
            SET harga_pokok_rata_rata = NEW.harga_perolehan_satuan
            WHERE id_barang = NEW.id_barang
              AND stok > 0
              AND harga_pokok_rata_rata = 0
              AND stok = NEW.jumlah;
        END IF;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Jumlah harus sama dengan stok saat ini. Muat ulang data dan coba lagi.';
        END IF;

        NEW.nilai_persediaan := ROUND(NEW.jumlah * NEW.harga_perolehan_satuan, 2);
    ELSIF NEW.jenis_transaksi = 'SALDO_AWAL' THEN
        IF COALESCE(NEW.harga_perolehan_satuan, 0) <= 0 THEN
            RAISE EXCEPTION 'Harga perolehan saldo awal wajib lebih dari 0';
        END IF;

        IF NEW.id_bahan IS NOT NULL THEN
            SELECT stok, harga_pokok_rata_rata
            INTO stok_bahan_saat_ini, harga_bahan_saat_ini
            FROM public.bahan_baku
            WHERE id_bahan = NEW.id_bahan
            FOR UPDATE;

            IF NOT FOUND THEN
                RAISE EXCEPTION 'Bahan saldo awal tidak ditemukan';
            END IF;
            IF stok_bahan_saat_ini > 0 AND harga_bahan_saat_ini <= 0 THEN
                RAISE EXCEPTION 'Nilai stok lama belum diketahui. Gunakan Penilaian Stok Lama terlebih dahulu.';
            END IF;

            UPDATE public.bahan_baku
            SET harga_pokok_rata_rata = CASE
                    WHEN stok + NEW.jumlah = 0 THEN 0
                    ELSE ROUND(
                        (stok * harga_pokok_rata_rata
                        + NEW.jumlah * NEW.harga_perolehan_satuan)
                        / (stok + NEW.jumlah),
                        4
                    )
                END,
                stok = stok + NEW.jumlah
            WHERE id_bahan = NEW.id_bahan;
        ELSE
            IF NEW.jumlah <> TRUNC(NEW.jumlah) THEN
                RAISE EXCEPTION 'Jumlah saldo awal barang jadi harus bilangan bulat';
            END IF;

            SELECT stok, harga_pokok_rata_rata
            INTO stok_bahan_saat_ini, harga_bahan_saat_ini
            FROM public.barang_jadi
            WHERE id_barang = NEW.id_barang
            FOR UPDATE;

            IF NOT FOUND THEN
                RAISE EXCEPTION 'Barang saldo awal tidak ditemukan';
            END IF;
            IF stok_bahan_saat_ini > 0 AND harga_bahan_saat_ini <= 0 THEN
                RAISE EXCEPTION 'Nilai stok lama belum diketahui. Gunakan Penilaian Stok Lama terlebih dahulu.';
            END IF;

            UPDATE public.barang_jadi
            SET harga_pokok_rata_rata = CASE
                    WHEN stok + NEW.jumlah = 0 THEN 0
                    ELSE ROUND(
                        (stok * harga_pokok_rata_rata
                        + NEW.jumlah * NEW.harga_perolehan_satuan)
                        / (stok + NEW.jumlah),
                        4
                    )
                END,
                stok = stok + NEW.jumlah::INTEGER
            WHERE id_barang = NEW.id_barang;
        END IF;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Barang saldo awal tidak ditemukan';
        END IF;

        NEW.nilai_persediaan := ROUND(NEW.jumlah * NEW.harga_perolehan_satuan, 2);
    ELSIF NEW.jenis_transaksi = 'MASUK' THEN
        IF COALESCE(NEW.harga_perolehan_satuan, 0) <= 0 THEN
            RAISE EXCEPTION 'Harga perolehan bahan wajib lebih dari 0';
        END IF;

        IF NEW.metode_pembayaran IS NULL THEN
            RAISE EXCEPTION 'Metode pembayaran pembelian wajib dipilih';
        END IF;

        SELECT stok, harga_pokok_rata_rata
        INTO stok_bahan_saat_ini, harga_bahan_saat_ini
        FROM public.bahan_baku
        WHERE id_bahan = NEW.id_bahan
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Bahan baku tidak ditemukan';
        END IF;
        IF stok_bahan_saat_ini > 0 AND harga_bahan_saat_ini <= 0 THEN
            RAISE EXCEPTION 'Nilai stok lama belum diketahui. Catat Penilaian Stok Lama terlebih dahulu.';
        END IF;

        UPDATE public.bahan_baku
        SET harga_pokok_rata_rata = CASE
                WHEN stok + NEW.jumlah = 0 THEN 0
                ELSE ROUND(
                    (stok * harga_pokok_rata_rata
                    + NEW.jumlah * NEW.harga_perolehan_satuan)
                    / (stok + NEW.jumlah),
                    4
                )
            END,
            stok = stok + NEW.jumlah
        WHERE id_bahan = NEW.id_bahan;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Bahan baku tidak ditemukan';
        END IF;

        NEW.nilai_persediaan := ROUND(NEW.jumlah * NEW.harga_perolehan_satuan, 2);
    ELSIF NEW.jenis_transaksi = 'BAHAN_KELUAR' THEN
        UPDATE public.bahan_baku
        SET stok = stok - NEW.jumlah
        WHERE id_bahan = NEW.id_bahan
          AND stok >= NEW.jumlah
        RETURNING harga_pokok_rata_rata INTO harga_unit;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Stok bahan baku tidak mencukupi atau bahan tidak ditemukan';
        END IF;
        IF harga_unit <= 0 THEN
            RAISE EXCEPTION 'Harga pokok bahan belum tersedia. Catat Penilaian Stok Lama terlebih dahulu.';
        END IF;

        NEW.nilai_persediaan := ROUND(NEW.jumlah * harga_unit, 2);
    ELSIF NEW.jenis_transaksi = 'KELUAR' THEN
        IF NEW.jumlah <> TRUNC(NEW.jumlah) THEN
            RAISE EXCEPTION 'Jumlah barang jadi harus bilangan bulat';
        END IF;

        IF COALESCE(NEW.harga_jual_satuan, 0) <= 0 THEN
            RAISE EXCEPTION 'Harga jual per unit wajib lebih dari 0';
        END IF;

        IF NEW.metode_pembayaran IS NULL THEN
            RAISE EXCEPTION 'Metode pembayaran penjualan wajib dipilih';
        END IF;

        UPDATE public.barang_jadi
        SET stok = stok - NEW.jumlah::INTEGER
        WHERE id_barang = NEW.id_barang
          AND stok >= NEW.jumlah
        RETURNING harga_pokok_rata_rata INTO harga_unit;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Stok barang jadi tidak mencukupi atau barang tidak ditemukan';
        END IF;

        IF harga_unit <= 0 THEN
            RAISE EXCEPTION 'Harga pokok barang belum tersedia. Catat saldo awal bernilai atau produksi barang terlebih dahulu.';
        END IF;

        NEW.nilai_persediaan := ROUND(NEW.jumlah * harga_unit, 2);
        NEW.nilai_penjualan := ROUND(NEW.jumlah * NEW.harga_jual_satuan, 2);
    ELSIF NEW.jenis_transaksi = 'PRODUKSI' THEN
        IF NEW.jumlah <> TRUNC(NEW.jumlah) THEN
            RAISE EXCEPTION 'Jumlah produksi harus bilangan bulat';
        END IF;

        IF NOT EXISTS (
            SELECT 1
            FROM public.detail_produksi
            WHERE id_barang = NEW.id_barang
        ) THEN
            RAISE EXCEPTION 'Resep produksi barang belum dibuat';
        END IF;

        IF EXISTS (
            SELECT 1
            FROM public.detail_produksi AS dp
            JOIN public.bahan_baku AS bb ON bb.id_bahan = dp.id_bahan
            WHERE dp.id_barang = NEW.id_barang
              AND NOT bb.aktif
        ) THEN
            RAISE EXCEPTION 'Resep menggunakan bahan baku yang sudah diarsipkan. Perbarui bahan habis pakai terlebih dahulu.';
        END IF;

        FOR detail IN
            SELECT dp.id_bahan, dp.jumlah_digunakan, bb.nama_bahan,
                   bb.harga_pokok_rata_rata
            FROM public.detail_produksi AS dp
            JOIN public.bahan_baku AS bb ON bb.id_bahan = dp.id_bahan
            WHERE dp.id_barang = NEW.id_barang
            ORDER BY dp.id_bahan
        LOOP
            kebutuhan := detail.jumlah_digunakan * NEW.jumlah;
            IF detail.harga_pokok_rata_rata <= 0 THEN
                RAISE EXCEPTION 'Harga pokok bahan "%" belum tersedia. Catat Penilaian Stok Lama terlebih dahulu.',
                    detail.nama_bahan;
            END IF;
            biaya_bahan_total := biaya_bahan_total
                + ROUND(kebutuhan * detail.harga_pokok_rata_rata, 2);

            UPDATE public.bahan_baku
            SET stok = stok - kebutuhan
            WHERE id_bahan = detail.id_bahan
              AND stok >= kebutuhan;

            IF NOT FOUND THEN
                SELECT COALESCE(stok, 0)
                INTO stok_bahan_saat_ini
                FROM public.bahan_baku
                WHERE id_bahan = detail.id_bahan;

                RAISE EXCEPTION
                    'Stok bahan "%" tidak mencukupi. Dibutuhkan: %, tersedia: %',
                    detail.nama_bahan,
                    kebutuhan,
                    COALESCE(stok_bahan_saat_ini, 0);
            END IF;
        END LOOP;

        IF biaya_bahan_total <= 0 THEN
            RAISE EXCEPTION 'Nilai bahan baku belum tersedia. Catat saldo awal atau pembelian bahan dengan harga perolehan terlebih dahulu.';
        END IF;

        SELECT stok, harga_pokok_rata_rata
        INTO stok_bahan_saat_ini, harga_bahan_saat_ini
        FROM public.barang_jadi
        WHERE id_barang = NEW.id_barang
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Barang jadi tidak ditemukan';
        END IF;
        IF stok_bahan_saat_ini > 0 AND harga_bahan_saat_ini <= 0 THEN
            RAISE EXCEPTION 'Harga pokok stok barang lama belum diketahui. Catat Penilaian Stok Lama terlebih dahulu.';
        END IF;

        IF COALESCE(NEW.biaya_produksi, 0) > 0 AND NEW.metode_pembayaran IS NULL THEN
            RAISE EXCEPTION 'Pilih metode pembayaran untuk biaya produksi tambahan';
        END IF;

        nilai_produksi_total := biaya_bahan_total + COALESCE(NEW.biaya_produksi, 0);
        NEW.nilai_bahan := biaya_bahan_total;
        NEW.nilai_persediaan := nilai_produksi_total;

        UPDATE public.barang_jadi
        SET harga_pokok_rata_rata = ROUND(
                (stok * harga_pokok_rata_rata + nilai_produksi_total)
                / (stok + NEW.jumlah),
                4
            ),
            stok = stok + NEW.jumlah::INTEGER
        WHERE id_barang = NEW.id_barang
        RETURNING harga_pokok_rata_rata INTO harga_unit;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Barang jadi tidak ditemukan';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.catat_jurnal_transaksi()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    akun_kas VARCHAR(100);
BEGIN
    akun_kas := CASE
        WHEN NEW.metode_pembayaran = 'TUNAI' THEN 'Kas'
        ELSE 'Bank'
    END;

    IF NEW.jenis_transaksi = 'MASUK' THEN
        INSERT INTO public.jurnal_umum
            (id_transaksi, tanggal, akun, debit, kredit, keterangan)
        VALUES
            (NEW.id_transaksi, NEW.tanggal, 'Persediaan Bahan Baku',
             NEW.nilai_persediaan, 0, 'Pembelian bahan baku'),
            (NEW.id_transaksi, NEW.tanggal, akun_kas,
             0, NEW.nilai_persediaan, 'Pembayaran pembelian bahan baku');
    ELSIF NEW.jenis_transaksi IN ('SALDO_AWAL', 'PENILAIAN_AWAL') THEN
        INSERT INTO public.jurnal_umum
            (id_transaksi, tanggal, akun, debit, kredit, keterangan)
        VALUES
            (NEW.id_transaksi, NEW.tanggal,
             CASE WHEN NEW.id_bahan IS NOT NULL
                  THEN 'Persediaan Bahan Baku'
                  ELSE 'Persediaan Barang Jadi'
             END,
             NEW.nilai_persediaan, 0, 'Pengakuan saldo awal persediaan'),
            (NEW.id_transaksi, NEW.tanggal, 'Modal Pemilik',
             0, NEW.nilai_persediaan, 'Saldo awal persediaan');
    ELSIF NEW.jenis_transaksi = 'BAHAN_KELUAR' THEN
        INSERT INTO public.jurnal_umum
            (id_transaksi, tanggal, akun, debit, kredit, keterangan)
        VALUES
            (NEW.id_transaksi, NEW.tanggal, 'Beban Bahan Baku',
             NEW.nilai_persediaan, 0, 'Pemakaian bahan di luar produksi'),
            (NEW.id_transaksi, NEW.tanggal, 'Persediaan Bahan Baku',
             0, NEW.nilai_persediaan, 'Pengurangan bahan baku');
    ELSIF NEW.jenis_transaksi = 'PRODUKSI' THEN
        INSERT INTO public.jurnal_umum
            (id_transaksi, tanggal, akun, debit, kredit, keterangan)
        VALUES
            (NEW.id_transaksi, NEW.tanggal, 'Persediaan Barang Jadi',
             NEW.nilai_persediaan, 0, 'Pemindahan biaya produksi ke barang jadi'),
            (NEW.id_transaksi, NEW.tanggal, 'Persediaan Bahan Baku',
             0, NEW.nilai_bahan, 'Bahan baku yang digunakan dalam produksi');

        IF NEW.biaya_produksi > 0 THEN
            INSERT INTO public.jurnal_umum
                (id_transaksi, tanggal, akun, debit, kredit, keterangan)
            VALUES
                (NEW.id_transaksi, NEW.tanggal, akun_kas,
                 0, NEW.biaya_produksi, 'Pembayaran biaya produksi tambahan');
        END IF;
    ELSIF NEW.jenis_transaksi = 'KELUAR' THEN
        INSERT INTO public.jurnal_umum
            (id_transaksi, tanggal, akun, debit, kredit, keterangan)
        VALUES
            (NEW.id_transaksi, NEW.tanggal, akun_kas,
